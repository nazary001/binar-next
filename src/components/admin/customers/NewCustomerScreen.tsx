// /admin/customers/new: a new customer account, made the way the site and
// `npm run user:create` make one. A partner needs a company: an existing
// one or a new one made together with the account. The password is
// generated by the server (shown once after creation) or typed here.
//
// Other sections open the page filled in: ?company=<id> (a company page),
// ?name=&email=&phone=&companyName= (a form submission).

export type NewCustomerPreset = { companyId: string; name: string; email: string; phone: string; companyName: string };

type CompanyMode = "existing" | "new";
type PasswordMode = "generate" | "manual";

type Draft = {
  type: AccountType;
  name: string;
  login: string;
  email: string;
  phone: string;
  position: string;
  companyMode: CompanyMode;
  clientId: string | null;
  companyName: string;
  edrpou: string;
  region: string;
  city: string;
  // Sent for every new company, so the API's default never decides it.
  discount: number | null;
  role: AccessRole;
  passwordMode: PasswordMode;
  password: string;
};

type Errors = Partial<Record<keyof Draft, string>>;

function draftOf(preset: NewCustomerPreset): Draft {
  const phone = preset.phone && isValidPhone(preset.phone) ? phoneDigits(preset.phone) : preset.phone;
  // A phone signs in more often than an e-mail in this trade. An e-mail
  // that became the login is not repeated in the e-mail field (the API
  // takes the login as the e-mail then), and neither is a phone.
  const login = phone && isValidPhone(phone) ? phone : preset.email;
  return {
    type: "b2b",
    name: preset.name,
    login,
    email: login === preset.email ? "" : preset.email,
    phone: login === phone ? "" : phone,
    position: "",
    companyMode: preset.companyId ? "existing" : preset.companyName ? "new" : "existing",
    clientId: preset.companyId || null,
    companyName: preset.companyName,
    edrpou: "",
    region: "",
    city: "",
    discount: 0,
    role: "b2b_admin",
    passwordMode: "generate",
    password: "",
  };
}

const LOGIN_INVALID = "Вкажіть e-mail або мобільний номер у форматі 0XX XXX XX XX";
const PHONE_INVALID = "Вкажіть номер у форматі 0XX XXX XX XX";
const EMAIL_INVALID = "Перевірте адресу: name@example.com";

function validate(draft: Draft): Errors {
  const errors: Errors = {};
  const b2b = draft.type === "b2b";
  if (!draft.name.trim()) errors.name = "Вкажіть ім'я та прізвище";
  if (!draft.login.trim()) errors.login = "Вкажіть логін: e-mail або телефон";
  else if (!isValidLogin(draft.login.trim())) errors.login = LOGIN_INVALID;
  if (draft.email.trim() && !isValidEmail(draft.email)) errors.email = EMAIL_INVALID;
  if (draft.phone.trim() && nationalPhone(draft.phone) === null) errors.phone = PHONE_INVALID;
  if (b2b && draft.companyMode === "existing" && !draft.clientId) errors.clientId = "Оберіть компанію";
  if (b2b && draft.companyMode === "new") {
    if (!draft.companyName.trim()) errors.companyName = "Вкажіть назву компанії";
    if (draft.edrpou.trim() && !isValidCode(draft.edrpou)) errors.edrpou = "8 цифр ЄДРПОУ або 10 цифр ІПН";
    if (draft.discount !== null && (draft.discount < 0 || draft.discount >= 100)) errors.discount = "Від 0 до 99,99 %";
  }
  if (draft.passwordMode === "manual" && draft.password.length < CUSTOMER_PASSWORD_MIN) {
    errors.password = `Щонайменше ${CUSTOMER_PASSWORD_MIN} символів`;
  }
  return errors;
}

function bodyOf(draft: Draft): CreateCustomerBody {
  const b2b = draft.type === "b2b";
  const text = (value: string) => value.trim() || undefined;
  return {
    type: draft.type,
    login: draft.login.trim(),
    name: draft.name.trim(),
    email: text(draft.email),
    phone: text(draft.phone),
    position: b2b ? text(draft.position) : undefined,
    password: draft.passwordMode === "manual" ? draft.password : undefined,
    company: b2b
      ? draft.companyMode === "existing"
        ? { clientId: draft.clientId ?? "" }
        : {
            name: draft.companyName.trim(),
            edrpou: text(draft.edrpou),
            region: text(draft.region),
            city: text(draft.city),
            discountPercent: draft.discount ?? 0,
          }
      : undefined,
    role: b2b ? draft.role : undefined,
  };
}

// API field keys -> form fields, and the sentences more exact than the
// shared reasons.
const RENAME: Record<string, keyof Draft> = {
  company: "clientId",
  "company.clientId": "clientId",
  "company.name": "companyName",
  "company.edrpou": "edrpou",
};
const OWN_REASONS: Record<string, Record<string, string>> = {
  login: { invalid: LOGIN_INVALID, required: "Вкажіть логін: e-mail або телефон" },
  email: { invalid: EMAIL_INVALID },
  phone: { invalid: PHONE_INVALID },
  name: { required: "Вкажіть ім'я та прізвище" },
  "company.clientId": { "not-found": "Цієї компанії вже немає: оберіть іншу" },
  "company.edrpou": { invalid: "8 цифр ЄДРПОУ або 10 цифр ІПН" },
  company: { required: "Оберіть компанію" },
};

// Takes the manager to the first field with a message (it may be far up
// the page), once React has drawn the messages.
function focusFirstError(): void {
  window.requestAnimationFrame(() => {
    const field = document.querySelector<HTMLElement>("form [aria-invalid='true']");
    if (!field) return;
    field.focus({ preventScroll: true });
    field.scrollIntoView({ block: "center", behavior: "smooth" });
  });
}

// --- the two type tiles ----------------------------------------------------------

type TypeOption = { value: AccountType; title: string; text: string; icon: ComponentType<SVGProps<SVGSVGElement>> };

const TYPES: TypeOption[] = [
  { value: "b2b", title: "Партнер B2B", text: "Бачить партнерські ціни і кабінет компанії: замовлення, документи, розрахунки.", icon: BuildingOffice2Icon },
  { value: "b2c", title: "Покупець B2C", text: "Роздрібний покупець: роздрібні ціни, кошик і власні замовлення.", icon: ShoppingBagIcon },
];

function TypeTiles({ value, onChange }: { value: AccountType; onChange: (value: AccountType) => void }) {
  return (
    <div role="radiogroup" aria-label="Тип акаунта" className="grid gap-3 min-[640px]:grid-cols-2">
      {TYPES.map((option) => {
        const on = option.value === value;
        const Icon = option.icon;
        return (
          <label
            key={option.value}
            data-type-tile={option.value}
            className={cx(
              "relative flex min-w-0 cursor-pointer flex-col gap-4 rounded-2xl border p-5 motion-reduce:transition-none",
              COLOR_TRANSITION,
              "has-[input:focus-visible]:ring-2 has-[input:focus-visible]:ring-brand has-[input:focus-visible]:ring-offset-2",
              on ? "border-brand bg-white ring-1 ring-brand" : "border-stroke-subtle bg-white hover:border-neutral-400",
            )}
          >
            <input
              type="radio"
              name="account-type"
              value={option.value}
              checked={on}
              onChange={() => onChange(option.value)}
              className="peer absolute inset-0 m-0 size-full cursor-pointer appearance-none opacity-0"
            />
            <span className="flex items-start justify-between gap-3">
              <span
                aria-hidden
                className={cx(
                  "flex size-11 shrink-0 items-center justify-center rounded-xl motion-reduce:transition-none",
                  COLOR_TRANSITION,
                  on ? "bg-neutral-900 text-white" : "bg-bg-cabinet text-neutral-800",
                )}
              >
                <Icon className="size-6" strokeWidth={1.7} />
              </span>
              <span
                aria-hidden
                className={cx(
                  "mt-0.5 block size-[18px] shrink-0 rounded-full border bg-white transition-[border-color,border-width] duration-200 motion-reduce:transition-none",
                  on ? "border-[5px] border-brand" : "border-neutral-400",
                )}
              />
            </span>
            <span className="flex flex-col gap-1">
              <span className={TEXT.cardTitle}>{option.title}</span>
              <span className={TEXT.muted}>{option.text}</span>
            </span>
          </label>
        );
      })}
    </div>
  );
}

// --- the screen ------------------------------------------------------------------

const COMPANY_MODES = [
  { value: "existing" as const, label: "Існуюча компанія" },
  { value: "new" as const, label: "Нова компанія" },
];

const ROLE_CHOICES = ACCESS_ROLES.map((role) => ({ value: role.value, label: role.label, hint: role.hint }));

const PASSWORD_MODES = [
  { value: "generate" as const, label: "Згенерувати пароль", hint: "Надійний пароль покажемо один раз після створення: передайте його людині." },
  { value: "manual" as const, label: "Задати вручну", hint: "Якщо пароль уже погоджено з людиною." },
];

const REGION_OPTIONS = REGIONS.map((region) => ({ value: region.value, label: region.label }));

export function NewCustomerScreen({ preset }: { preset: NewCustomerPreset }) {
  const router = useRouter();
  const [initial] = useState(() => draftOf(preset));
  const [draft, setDraft] = useState<Draft>(initial);
  const [errors, setErrors] = useState<Errors>({});
  const [busy, setBusy] = useState(false);
  const [created, setCreated] = useState<{ customer: CustomerDetail; password: string } | null>(null);
  const [leaving, setLeaving] = useState(false);
  const dirty = useDirty(initial, draft);
  // Once the account exists there is nothing left to lose here.
  useUnsavedWarning(dirty && !created && !leaving);
  const b2b = draft.type === "b2b";

  const set = <K extends keyof Draft>(key: K, value: Draft[K]) => {
    setDraft((current) => ({ ...current, [key]: value }));
    setErrors((current) => (current[key] ? { ...current, [key]: undefined } : current));
  };

  const openAccount = (customer: CustomerDetail) => {
    setLeaving(true);
    router.push(`/admin/customers/${encodeURIComponent(customer.id)}`);
  };

  const submit = async (event: FormEvent) => {
    event.preventDefault();
    if (busy) return;
    const found = validate(draft);
    if (Object.keys(found).length > 0) {
      setErrors(found);
      focusFirstError();
      return;
    }
    setBusy(true);
    const result = await adminApi<CreateCustomerAnswer>("/customers", { method: "POST", body: bodyOf(draft) });
    setBusy(false);
    if (!result.ok) {
      if (result.error === "exists") setErrors({ login: "Цей логін, телефон або e-mail уже відкриває інший акаунт" });
      else setErrors(fieldErrors(result, OWN_REASONS, RENAME) as Errors);
      // The messages sit under the fields; a toast would only cover the
      // sticky buttons. Other refusals have no field to point at.
      if (result.error === "fields" || result.error === "exists") focusFirstError();
      else toastError(result, CUSTOMER_ERRORS);
      return;
    }
    const { customer, password } = result.data;
    applyCustomer(customer);
    if (password) {
      setCreated({ customer, password });
      return;
    }
    toast.success("Акаунт створено");
    openAccount(customer);
  };

  return (
    <Page width="narrow">
      <PageHeader
        back={{ href: "/admin/customers", label: "До списку акаунтів" }}
        title="Новий"
        light="акаунт"
        subtitle="Акаунт для входу на сайт: партнера компанії або роздрібного покупця"
      />
      <form onSubmit={submit} noValidate className="flex flex-col gap-4" aria-label="Новий акаунт">
        <FormSection title="Тип акаунта" description="Від типу залежать ціни, які людина бачить на сайті, і її кабінет.">
          <TypeTiles value={draft.type} onChange={(type) => set("type", type)} />
        </FormSection>

        <FormSection title="Людина" description="Ім'я та контакти. За логіном людина входитиме на сайт.">
          <FormGrid>
            <Input
              label="Ім'я та прізвище"
              value={draft.name}
              onChange={(value) => set("name", value)}
              error={errors.name}
              maxLength={CUSTOMER_NAME_MAX}
              required
              autoComplete="off"
              placeholder="Олена Коваль"
              className="col-span-full"
            />
            <Input
              label="Логін"
              value={draft.login}
              onChange={(value) => set("login", value)}
              error={errors.login}
              maxLength={CUSTOMER_EMAIL_MAX}
              required
              autoComplete="off"
              autoCapitalize="none"
              spellCheck={false}
              placeholder="0XX XXX XX XX або name@example.com"
              hint="Мобільний номер або e-mail. Змінити логін потім не можна"
              className="col-span-full"
            />
            <Input
              label="E-mail"
              type="email"
              inputMode="email"
              value={draft.email}
              onChange={(value) => set("email", value)}
              error={errors.email}
              maxLength={CUSTOMER_EMAIL_MAX}
              optional
              autoComplete="off"
              placeholder="name@example.com"
              hint="Теж відкриватиме акаунт"
            />
            <Input
              label="Телефон"
              type="tel"
              inputMode="tel"
              value={draft.phone}
              onChange={(value) => set("phone", value)}
              error={errors.phone}
              maxLength={32}
              optional
              autoComplete="off"
              placeholder="0XX XXX XX XX"
              hint="Якщо логін - e-mail, з номером теж можна увійти"
            />
            {b2b && (
              <Input
                label="Посада"
                value={draft.position}
                onChange={(value) => set("position", value)}
                maxLength={CUSTOMER_POSITION_MAX}
                optional
                autoComplete="off"
                placeholder="Наприклад, менеджер із закупівель"
                className="col-span-full"
              />
            )}
          </FormGrid>
        </FormSection>

        {b2b && (
          <FormSection title="Компанія" description="Партнер працює від імені компанії: бачить її ціни, замовлення й документи.">
            <div className="flex flex-col gap-5">
              <RadioGroup
                aria-label="Компанія партнера"
                value={draft.companyMode}
                onChange={(mode) => set("companyMode", mode)}
                options={COMPANY_MODES}
                direction="horizontal"
              />
              {draft.companyMode === "existing" ? (
                <CompanyPicker
                  label="Компанія"
                  value={draft.clientId}
                  onChange={(id) => set("clientId", id)}
                  error={errors.clientId}
                  required
                  hint="Знайдіть за назвою або ЄДРПОУ"
                />
              ) : (
                <FormGrid>
                  <Input
                    label="Назва компанії"
                    value={draft.companyName}
                    onChange={(value) => set("companyName", value)}
                    error={errors.companyName}
                    maxLength={COMPANY_NAME_MAX}
                    required
                    autoComplete="off"
                    placeholder="ТОВ «Готель Дністер»"
                    className="col-span-full"
                  />
                  <Input
                    label="ЄДРПОУ або ІПН"
                    value={draft.edrpou}
                    onChange={(value) => set("edrpou", value.replace(/\D/g, ""))}
                    error={errors.edrpou}
                    inputMode="numeric"
                    maxLength={10}
                    optional
                    autoComplete="off"
                    placeholder="12345678"
                  />
                  <NumberInput
                    label="Знижка"
                    value={draft.discount}
                    onChange={(value) => set("discount", value)}
                    error={errors.discount}
                    min={0}
                    max={99.99}
                    step={0.5}
                    suffix="%"
                    hint="Від базових цін сайту. 0 - без знижки"
                  />
                  <NativeSelect
                    label="Область"
                    value={draft.region}
                    onChange={(value) => set("region", value)}
                    options={REGION_OPTIONS}
                    placeholder="Не вказано"
                    optional
                  />
                  <Input
                    label="Місто"
                    value={draft.city}
                    onChange={(value) => set("city", value)}
                    maxLength={COMPANY_CITY_MAX}
                    optional
                    autoComplete="off"
                    placeholder="Львів"
                  />
                </FormGrid>
              )}
              <RadioGroup
                label="Доступ у кабінеті"
                value={draft.role}
                onChange={(role) => set("role", role)}
                options={ROLE_CHOICES}
                variant="tiles"
                direction="horizontal"
              />
            </div>
          </FormSection>
        )}

        <FormSection title="Пароль" description="Пароль зберігається лише в зашифрованому вигляді: подивитися його потім не вийде.">
          <div className="flex flex-col gap-5">
            <RadioGroup
              aria-label="Як задати пароль"
              value={draft.passwordMode}
              onChange={(mode) => set("passwordMode", mode)}
              options={PASSWORD_MODES}
              variant="tiles"
              direction="horizontal"
            />
            {draft.passwordMode === "manual" && (
              <PasswordInput
                label="Пароль"
                value={draft.password}
                onChange={(value) => set("password", value)}
                error={errors.password}
                hint={`Щонайменше ${CUSTOMER_PASSWORD_MIN} символів`}
                generate
                required
              />
            )}
          </div>
        </FormSection>

        <FormActions sticky status={dirty ? "Акаунт ще не створено" : undefined}>
          <Button variant="secondary" href="/admin/customers">
            Скасувати
          </Button>
          <Button type="submit" loading={busy}>
            Створити акаунт
          </Button>
        </FormActions>
      </form>

      <Modal
        open={created !== null}
        onClose={() => created && openAccount(created.customer)}
        closeOnScrim={false}
        title="Акаунт створено"
        description="Передайте людині логін і пароль: з ними вона увійде на сайт."
        footer={<Button onClick={() => created && openAccount(created.customer)}>Перейти до акаунта</Button>}
      >
        {created && <OneTimeSecret login={created.customer.login} password={created.password} />}
      </Modal>
    </Page>
  );
}
